import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const phoneRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.resolve(phoneRoot, "../app/src-tauri/migrations");
const destDir = path.resolve(phoneRoot, "assets/migrations");
const generated = path.resolve(phoneRoot, "src/db/migrations.generated.ts");

const names = (await readdir(sourceDir)).filter((name) => name.endsWith(".sql")).sort();
await rm(destDir, { recursive: true, force: true });
await mkdir(destDir, { recursive: true });

const files = [];
for (const name of names) {
  const version = Number(/^(\d+)/.exec(name)?.[1]);
  if (!Number.isInteger(version)) throw new Error(`migration name has no version: ${name}`);
  const sql = await readFile(path.join(sourceDir, name), "utf8");
  await writeFile(path.join(destDir, name), sql);
  files.push({ version, sql });
}

const body = `// Generated by scripts/copy-migrations.mjs. The Tauri SQL files stay the source of truth.\nexport const migrations: { version: number; sql: string }[] = ${JSON.stringify(files, null, 2)};\n`;
await mkdir(path.dirname(generated), { recursive: true });
await writeFile(generated, body);
